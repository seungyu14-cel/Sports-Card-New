def training_profile(agent_id: str) -> dict[str, Any]:
    profile = EMPLOYEE_TRAINING.get(agent_id)
    if profile is None:
        return {
            "name": agent_id,
            "focus": "공통 검수",
            "core_rule": "MD 원문 범위 안에서 담당 역할을 수행한다.",
            "study_topics": [],
            "decision_rules": ["MD에 없는 사실을 추가하지 않는다."],
            "checklist": ["최종 결과가 MD 근거를 벗어나지 않는가"],
            "forbidden": ["외부 지식으로 사실 보완"],
        }
    return profile


def training_payload(agent_ids: list[str]) -> list[dict[str, Any]]:
    return [{"agent_id": agent_id, **training_profile(agent_id)} for agent_id in agent_ids]


def training_summary(agent_id: str) -> str:
    profile = training_profile(agent_id)
    rules = " / ".join(profile["decision_rules"])
    forbidden = " / ".join(profile["forbidden"])
    return (
        f"[{profile['name']}] 집중 분야: {profile['focus']}\n"
        f"핵심 규칙: {profile['core_rule']}\n"
        f"판단 규칙: {rules}\n"
        f"금지: {forbidden}"
    )
